"""Paired Responses Loader for loading paired tabular data features."""

import logging
import typing as t
from pathlib import Path

import numpy as np
import torch

logger = logging.getLogger(__name__)


class PairedResponsesLoader:
    """
    A utility class for loading paired responses generated by PairedResponsesHook.

    Unlike the standard ResponsesLoader which expects subset-based organization, this loader
    handles paired data saved in a simple module_name/id.pt structure.

    File structure expected:
    root/
    ├── module_name_1/
    │   ├── pair_id_1.pt
    │   ├── pair_id_2.pt
    │   └── ...
    └── module_name_2/
        ├── pair_id_1.pt
        └── ...

    Each .pt file contains a single sample with features and metadata.
    """

    def __init__(
        self,
        root: Path,
        columns: t.List[str] = None,
    ):
        """Initialize PairedResponsesLoader.

        Args:
            root: Root directory containing paired response files
            columns: Specific columns to include in loaded data
        """
        self.root = Path(root)
        self.columns = columns or ["id", "features", "module_names"]

        # Discovery of available modules and pair IDs
        self.available_modules = []
        self.available_pairs = set()
        self._discover_structure()

    def _discover_structure(self):
        """Discover available modules and pair IDs from directory structure."""
        if not self.root.exists():
            logger.warning(f"Root directory {self.root} does not exist")
            return

        for module_dir in self.root.iterdir():
            if module_dir.is_dir():
                self.available_modules.append(module_dir.name)

                # Discover pair IDs in this module
                for pair_file in module_dir.glob("*.pt"):
                    pair_id = pair_file.stem  # Remove .pt extension
                    self.available_pairs.add(pair_id)

        logger.info(
            f"Found {len(self.available_modules)} modules and {len(self.available_pairs)} pairs"
        )
        logger.debug(f"Modules: {self.available_modules}")

    def load_data_subset(
        self,
        attribute_values: t.Dict[str, t.List[str]],
        num_workers: int = 0,
        batch_size: int = 128,
        multi_output: bool = True,
    ) -> dict:
        """Load paired data subset with interface compatible with ResponsesLoader.

        Args:
            attribute_values: Dictionary with module_names and other filters
            num_workers: Number of workers (not used, for compatibility)
            batch_size: Batch size (not used, for compatibility)
            multi_output: Multi output flag (not used, for compatibility)

        Returns:
            Dictionary compatible with intervention learning pipeline
        """
        logger.info(f"Loading paired data subset: {attribute_values}")

        module_names = attribute_values.get("module_names", self.available_modules)

        # Filter to available modules
        available_modules = [m for m in module_names if m in self.available_modules]
        if len(available_modules) != len(module_names):
            missing = set(module_names) - set(available_modules)
            logger.warning(f"Modules not found: {missing}")

        if not available_modules:
            raise ValueError(f"No data found for modules: {module_names}")

        # Load data from all modules
        all_responses = []
        all_ids = []
        all_module_names = []

        for module_name in available_modules:
            module_path = self.root / module_name

            # Load all pairs for this module
            pair_files = list(module_path.glob("*.pt"))
            logger.info(f"Loading {len(pair_files)} pairs from {module_name}")

            for pair_file in pair_files:
                try:
                    data = torch.load(pair_file, map_location="cpu", weights_only=True)

                    # Handle paired data structure with source_features and target_features
                    if "source_features" in data and "target_features" in data:
                        # For paired data, package both source and target features
                        pair_data = {
                            "source_features": data["source_features"],
                            "target_features": data["target_features"],
                            "id": data["id"],
                            "module_name": data["module_name"],
                        }
                        # Add any additional fields that might be present
                        if "row_data" in data:
                            pair_data["row_data"] = data["row_data"]
                        if "source_tokens" in data:
                            pair_data["source_tokens"] = data["source_tokens"]
                        if "target_tokens" in data:
                            pair_data["target_tokens"] = data["target_tokens"]

                        features = pair_data  # Pass the full paired structure

                    elif "features" in data:
                        # Fallback for standard format
                        features = data["features"]
                    else:
                        raise KeyError(
                            "Missing both paired features (source_features, target_features) and standard features"
                        )

                    pair_id = data["id"]

                    # Convert to numpy and add to collections
                    all_responses.append(features)  # Keep as dict for paired data
                    all_ids.append(pair_id)
                    all_module_names.append(module_name)

                except Exception as e:
                    logger.error(f"Failed to load {pair_file}: {e}")
                    continue

        if not all_responses:
            raise ValueError("No valid paired data found")

        # For paired data, we need to handle the structure differently
        if all_responses and isinstance(all_responses[0], dict):
            # Paired data: keep as list of dictionaries
            result = {
                "responses": all_responses,  # List of paired data dicts
                "id": np.array(all_ids),
                "module_names": np.array(all_module_names),
            }
        else:
            # Standard data: convert to numpy arrays
            result = {
                "responses": np.stack(all_responses).astype(np.float32),
                "id": np.array(all_ids),
                "module_names": np.array(all_module_names),
            }

        # Log appropriately based on data type
        if isinstance(result["responses"], list):
            logger.info(
                f"Loaded {len(result['responses'])} paired samples (list of dicts)"
            )
        else:
            logger.info(
                f"Loaded {len(result['responses'])} samples with shape {result['responses'].shape}"
            )
        return result


def subsample_paired_responses(
    responses: dict,
    size: int,
    seed: int = 42,
) -> dict:
    """Subsample paired responses to a specific size.

    Args:
        responses: Dictionary with response data
        size: Target size for subsampling
        seed: Random seed for reproducibility

    Returns:
        Subsampled responses dictionary
    """
    logger.info(f"Subsampling paired responses to size {size}...")

    rng = np.random.RandomState(seed)
    # Handle both list (paired data) and numpy array formats
    if isinstance(responses["responses"], list):
        current_size = len(responses["responses"])
    else:
        current_size = responses["responses"].shape[0]

    if size >= current_size:
        logger.info(
            f"Requested size {size} >= current size {current_size}, returning original data"
        )
        return responses

    # Random sampling
    indices = rng.permutation(current_size)[:size]

    subsampled = {}
    for key, values in responses.items():
        if isinstance(values, np.ndarray):
            subsampled[key] = values[indices]
        elif isinstance(values, list):
            # Handle list data (paired responses)
            subsampled[key] = [values[i] for i in indices]
        else:
            subsampled[key] = [values[i] for i in indices]

    logger.info(
        f"Subsampled from {current_size} to {len(subsampled['responses'])} samples"
    )
    return subsampled
